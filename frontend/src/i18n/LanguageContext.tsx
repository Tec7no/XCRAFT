const STORAGE_KEY = 'fox_lang';

const LanguageContext = React.createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const { settings } = useSiteSettings();
    const [lang, setLangState] = React.useState<Lang>(() => {
        if (typeof window !== 'undefined') {
            const stored = localStorage.getItem(STORAGE_KEY);
            if (stored === 'ar' || stored === 'en') return stored;
        }
        return 'ar';
    });

    React.useEffect(() => {
        localStorage.setItem(STORAGE_KEY, lang);
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
        document.documentElement.lang = lang;
    }, [lang]);

    const setLang = React.useCallback((newLang: Lang) => {
        setLangState(newLang);
    }, []);

    const toggleLang = React.useCallback(() => {
        setLangState((prev) => (prev === 'en' ? 'ar' : 'en'));
    }, []);

    const t = React.useCallback(
        (key: string): string => {
            // Priority 1: Admin Site Settings (with safe access)
            const customTranslation = settings?.translations?.[lang]?.[key];
            if (customTranslation) {
                return customTranslation;
            }
            // Priority 2: Static file translations
            return translations[lang]?.[key] || key;
        },
        [lang, settings]
    );

    return (
        <LanguageContext.Provider value={{ lang, setLang, toggleLang, t }}>
            {children}
        </LanguageContext.Provider>
    );
};

export const useLanguage = (): LanguageContextType => {
    const context = React.useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
};
